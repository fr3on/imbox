#!/usr/bin/env node
// Turns a D1 data export (`wrangler d1 export <db> --remote --no-schema --output data.sql`) into a script that loads the same rows into the Postgres
// database the self-hosted server uses. The tables must already exist: start the server once so it applies the migrations.
//
//   node scripts/d1-to-pg.mjs data.sql > load.sql
//   sudo -u postgres psql -v ON_ERROR_STOP=1 -1 inbox -f load.sql
//
// The load replaces everything in the target's tables (except the migration log) inside one transaction, so a failure leaves it untouched.
import fs from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/d1-to-pg.mjs data.sql > load.sql");
  process.exit(1);
}
const src = fs.readFileSync(file, "utf8");

/** Split into statements at `;` outside string literals, and turn SQLite blob literals X'ab' into Postgres bytea input '\xab'. */
function statements(text) {
  const out = [];
  let cur = "";
  let i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === "'") {
      let j = i + 1;
      while (j < text.length) {
        if (text[j] === "'") {
          if (text[j + 1] === "'") j += 2;
          else break;
        } else j++;
      }
      const lit = text.slice(i, j + 1);
      const prev = cur.slice(-1);
      if ((prev === "X" || prev === "x") && !/[\w]/.test(cur.slice(-2, -1) || " ") && /^'[0-9a-fA-F]*'$/.test(lit)) cur = `${cur.slice(0, -1)}'\\x${lit.slice(1)}`;
      else cur += lit;
      i = j + 1;
    } else if (c === ";") {
      if (cur.trim()) out.push(cur.trim());
      cur = "";
      i++;
    } else {
      cur += c;
      i++;
    }
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

const SKIP = /^(PRAGMA|BEGIN|COMMIT)\b|^INSERT INTO "(d1_migrations|sqlite_sequence)"/i;
// D1 writes newlines inside text as replace('a\nb','\n',char(10)); Postgres calls the function chr.
const stmts = statements(src)
  .filter((s) => !SKIP.test(s))
  .map((s) => s.replace(/,char\((\d+)\)\)/g, ",chr($1))"));
const sequences = [...src.matchAll(/INSERT INTO "sqlite_sequence" \("name","seq"\) VALUES\('([a-z_0-9]+)',(\d+)\)/g)].map((m) => ({ table: m[1], seq: Number(m[2]) })).filter((s) => s.table !== "d1_migrations");

const lines = [];
lines.push("-- generated by scripts/d1-to-pg.mjs");
lines.push("SET session_replication_role = replica;"); // load in any table order; needs a superuser, which `sudo -u postgres` is
lines.push(`DO $$ DECLARE t text; BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename NOT IN ('d1_migrations') LOOP
    EXECUTE format('TRUNCATE TABLE %I CASCADE', t);
  END LOOP;
END $$;`);
for (const s of stmts) lines.push(`${s};`);
for (const { table, seq } of sequences) lines.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), ${seq}, true);`);
lines.push("SET session_replication_role = DEFAULT;");
process.stdout.write(`${lines.join("\n")}\n`);
console.error(`${stmts.length} statements, ${sequences.length} sequence(s)`);
