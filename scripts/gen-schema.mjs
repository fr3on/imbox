// Writes src/api/schema.ts: one row type per table, read from the migrated database. `node scripts/gen-schema.mjs` regenerates it
// (PG_TEST_URL names a scratch database); test/pg/schema.test.ts fails when the file and the migrations disagree.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import pg from "pg";
import { migrate } from "../server/pggateway.mjs";

const TYPES = {
  text: "string",
  "character varying": "string",
  integer: "number",
  bigint: "number",
  smallint: "number",
  real: "number",
  "double precision": "number",
  numeric: "number",
  boolean: "boolean",
  bytea: "ArrayBuffer",
  json: "unknown",
  jsonb: "unknown",
};

const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

/** The text of schema.ts for the tables in the connected database. */
export async function renderSchema(pool) {
  const { rows } = await pool.query(
    `SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name NOT IN ('d1_migrations', 'schema_migrations')
     ORDER BY table_name, ordinal_position`,
  );
  const tables = new Map();
  for (const r of rows) {
    const type = TYPES[r.data_type];
    if (!type) throw new Error(`gen-schema: no TypeScript type for ${r.table_name}.${r.column_name} (${r.data_type})`);
    if (!tables.has(r.table_name)) tables.set(r.table_name, []);
    tables.get(r.table_name).push(`  ${r.column_name}: ${type}${r.is_nullable === "YES" ? " | null" : ""};`);
  }
  const body = [...tables].map(([t, cols]) => `/** A row of \`${t}\`. */\nexport interface ${pascal(t)}Row {\n${cols.join("\n")}\n}`);
  return `// Generated by scripts/gen-schema.mjs from the migrations. Do not edit; run \`npm run gen:schema\`.\n\n${body.join("\n\n")}\n`;
}

export async function migratedPool(url, dir) {
  const pool = new pg.Pool({ connectionString: url, max: 2 });
  await pool.query("DROP SCHEMA public CASCADE; CREATE SCHEMA public;");
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().map((name) => ({ name, sql: fs.readFileSync(path.join(dir, name), "utf8") }));
  await migrate(pool, files);
  return pool;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const pool = await migratedPool(process.env.PG_TEST_URL ?? "postgres://inbox@localhost:54329/inbox_test", path.join(root, "migrations"));
  fs.writeFileSync(path.join(root, "src/api/schema.ts"), await renderSchema(pool));
  await pool.end();
}
